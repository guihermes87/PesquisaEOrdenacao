    private void jbuttonabrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbuttonabrirActionPerformed
        
            JFileChooser fc = new JFileChooser();
            if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            txtarquivo.setText(fc.getSelectedFile().getAbsolutePath());
}
        
        
        if (txtarquivo.getText().equals(" ")) {
            JOptionPane.showMessageDialog(this, "Informe o nome do arquivo", "Atenção", JOptionPane.ERROR_MESSAGE);
        } else {
            if (Util.CarregarArquivoEmLista(txtarquivo.getText(), Model.lista)){
            JOptionPane.showMessageDialog(this, "Lista carregada com sucesso", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Problemas ao carregar o arquivo", "Atenção", JOptionPane.ERROR_MESSAGE);
                txtarquivo.requestFocusInWindow();
            }
            
           
                
        }
    }//GEN-LAST:event_jbuttonabrirActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (Model.lista == null || Model.lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Carregue um arquivo com números antes de executar", "Atenção", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String metodo = (String) jComboBoxMetodos.getSelectedItem();
        ArrayList<Integer> listaOrdenar = new ArrayList<>(Model.lista);
        ArrayList<Float> metricas;

        long inicio = System.currentTimeMillis();
        switch (metodo) {
            case "Bolha":
                metricas = Ordenacao.bolha(listaOrdenar);
                break;
            case "Inserção":
                metricas = Ordenacao.insercao(listaOrdenar);
                break;
            case "Pente":
                metricas = Ordenacao.pente(listaOrdenar);
                break;
            case "Seleção":
                metricas = Ordenacao.selecao(listaOrdenar);
                break;
            default:
                JOptionPane.showMessageDialog(this, "Selecione um método de ordenação", "Atenção", JOptionPane.ERROR_MESSAGE);
                return;
        }
        long tempo = System.currentTimeMillis() - inicio;

        TxtNumeros.setText(String.valueOf(listaOrdenar.size()));
        TxtComparacoes.setText(String.valueOf(metricas.get(0).longValue()));
        TxtTrocas.setText(String.valueOf(metricas.get(1).longValue()));
        TxtTempo.setText(String.valueOf(tempo));

        jPanelResultados.setVisible(true);
    }//GEN-LAST:event_jButton1ActionPerformed

